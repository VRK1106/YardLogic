-- 1. Create Parking Slots Table
create table if not exists parking_slots (
  id text primary key,
  size_type text check (size_type in ('Small', 'Medium', 'Large')),
  status text default 'FREE',
  current_vehicle text
);

-- 2. Create Active Sessions Table
create table if not exists active_sessions (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  license_plate text,
  slot_id text references parking_slots(id),
  vehicle_type text,
  exit_time timestamptz,
  amount_paid numeric,
  payment_status text,
  is_active boolean default true,
  is_verified boolean default false
);

-- 3. Seed Initial Slots
insert into parking_slots (id, size_type) values
('A1', 'Small'), ('A2', 'Small'), ('A3', 'Small'), ('A4', 'Small'),
('B1', 'Medium'), ('B2', 'Medium'), ('B3', 'Medium'), ('B4', 'Medium'),
('C1', 'Large'), ('C2', 'Large'), ('C3', 'Large'), ('C4', 'Large')
on conflict (id) do nothing;
